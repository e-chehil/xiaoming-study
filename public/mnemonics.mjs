const storyShapes = {"": "亻", "": "刂", "": "讠", "": "忄", "": "扌", "": "氵", "": "犭", "": "礻", "": "纟", "": "衤", "": "钅", "": "饣", "": "冫", "": "阝"};

function soundAndStroke(image, rhyme, initials, stroke, note = '') {
  return {image, rhyme, initials, stroke, note, verse: image + '，' + rhyme + '。'};
}

